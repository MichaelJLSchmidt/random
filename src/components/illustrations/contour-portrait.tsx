const LEVELS = 14
const PER_GROUP = 2

/**
 * About: a portrait as 14 offset contour lines forming a head-and-shoulders silhouette, like a
 * topographic map of a bust; no facial features. 480×600, plain (no labels). Groups: seven, from
 * the outline inward (two levels each).
 */
export function ContourPortrait({ className, titleId, title = 'Contour portrait', description }: IllustrationProps) {
  const groups = Array.from({ length: Math.ceil(LEVELS / PER_GROUP) }, (_, g) =>
    contours.filter(([level]) => Math.floor(level / PER_GROUP) === g),
  )
  return (
    <IllustrationFrame
      slug="contour-portrait"
      viewBox={S}
      title={title}
      desc={
        description ??
        'A head-and-shoulders silhouette drawn as 14 nested contour lines, like a topographic map; the lines ring the head and arch over the shoulders. No face is drawn.'
      }
      className={className}
      titleId={titleId}
    >
      {groups.map((lines, g) => (
        <Group key={g} n={g + 1}>
          {lines.map(([level, d], i) => (
            <path key={i} d={d} data-level={level} pathLength="1" data-draw="" />
          ))}
        </Group>
      ))}
    </IllustrationFrame>
  )
}
